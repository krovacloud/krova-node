import type { Command } from "commander";

import { FLAG_VALUE_CHOICES } from "./output-format.js";

export const COMPLETION_SHELLS = ["bash", "zsh", "fish"] as const;
export type CompletionShell = (typeof COMPLETION_SHELLS)[number];

interface OptionNode {
  long?: string;
  short?: string;
  description: string;
  takesValue: boolean;
}

interface CommandNode {
  /** Canonical names from the root's first subcommand down; empty for the root. */
  path: string[];
  aliases: string[];
  description: string;
  options: OptionNode[];
  commands: CommandNode[];
}

const oneLine = (s: string): string => s.split("\n")[0]!.replace(/\s+/g, " ").trim();

/** Walk the commander tree (visible commands and options only). */
export function walkCommands(cmd: Command, path: string[] = []): CommandNode {
  const help = cmd.createHelp();
  return {
    path,
    aliases: cmd.aliases(),
    description: oneLine(cmd.description()),
    options: help.visibleOptions(cmd).map((o) => ({
      long: o.long,
      short: o.short,
      description: oneLine(o.description),
      takesValue: o.required || o.optional,
    })),
    commands: help.visibleCommands(cmd).map((c) => walkCommands(c, [...path, c.name()])),
  };
}

/** Shell single-quote: safe inside bash, zsh and fish single quotes. */
const sq = (s: string): string => `'${s.replace(/'/g, "'\\''")}'`;
const fishSq = (s: string): string => `'${s.replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;

const flat = (node: CommandNode): CommandNode[] => [node, ...node.commands.flatMap(flat)];
const key = (path: string[]): string => path.join(" ");
const optionWords = (n: CommandNode): string[] =>
  n.options.flatMap((o) => [o.long, o.short].filter((x): x is string => Boolean(x)));
const commandWords = (n: CommandNode): string[] => n.commands.flatMap((c) => [c.path.at(-1)!, ...c.aliases]);

/** Every (parent path, typed word) -> child path transition, aliases included. */
function transitions(root: CommandNode): Array<{ from: string; word: string; to: string }> {
  return flat(root).flatMap((parent) =>
    parent.commands.flatMap((c) =>
      [c.path.at(-1)!, ...c.aliases].map((word) => ({
        from: key(parent.path),
        word,
        to: key(c.path),
      }))
    )
  );
}

const choiceFlags = Object.keys(FLAG_VALUE_CHOICES);

function bash(root: CommandNode, name: string): string {
  const fn = `_${name}_complete`;
  const lines: string[] = [
    `# bash completion for ${name}, generated by \`${name} completion bash\``,
    `${fn}() {`,
    `  local cur prev cpath="" w next i`,
    `  cur="\${COMP_WORDS[COMP_CWORD]}"`,
    `  prev="\${COMP_WORDS[COMP_CWORD-1]}"`,
    `  for ((i=1; i<COMP_CWORD; i++)); do`,
    `    w="\${COMP_WORDS[i]}"`,
    `    next=""`,
    `    case "$cpath/$w" in`,
    ...transitions(root).map((t) => `      ${sq(`${t.from}/${t.word}`)}) next=${sq(t.to)};;`),
    `    esac`,
    `    [ -n "$next" ] && cpath="$next"`,
    `  done`,
    `  case "$prev" in`,
    `    ${choiceFlags.map(sq).join("|")}) COMPREPLY=( $(compgen -W ${sq(FLAG_VALUE_CHOICES[choiceFlags[0]!]!.join(" "))} -- "$cur") ); return;;`,
    `  esac`,
    `  local cmds="" opts=""`,
    `  case "$cpath" in`,
    ...flat(root).map(
      (n) =>
        `    ${sq(key(n.path))}) cmds=${sq(commandWords(n).join(" "))}; opts=${sq(optionWords(n).join(" "))};;`
    ),
    `  esac`,
    `  if [[ "$cur" == -* ]]; then`,
    `    COMPREPLY=( $(compgen -W "$opts" -- "$cur") )`,
    `  else`,
    `    COMPREPLY=( $(compgen -W "$cmds" -- "$cur") )`,
    `  fi`,
    `}`,
    `complete -o default -F ${fn} ${name}`,
  ];
  return `${lines.join("\n")}\n`;
}

function zsh(root: CommandNode, name: string): string {
  const fn = `_${name}`;
  const item = (word: string, desc: string): string =>
    sq(`${word.replace(/:/g, "\\:")}${desc ? `:${desc}` : ""}`);
  const lines: string[] = [
    `#compdef ${name}`,
    `# zsh completion for ${name}, generated by \`${name} completion zsh\``,
    `${fn}() {`,
    `  local cpath="" w next i`,
    `  local -a cmds opts`,
    `  for (( i=2; i<CURRENT; i++ )); do`,
    `    w="\${words[i]}"`,
    `    next=""`,
    `    case "$cpath/$w" in`,
    ...transitions(root).map((t) => `      ${sq(`${t.from}/${t.word}`)}) next=${sq(t.to)};;`),
    `    esac`,
    `    [[ -n "$next" ]] && cpath="$next"`,
    `  done`,
    `  case "\${words[CURRENT-1]}" in`,
    `    ${choiceFlags.map(sq).join("|")}) compadd -- ${FLAG_VALUE_CHOICES[choiceFlags[0]!]!.map(sq).join(" ")}; return;;`,
    `  esac`,
    `  case "$cpath" in`,
    ...flat(root).flatMap((n) => {
      const cmdItems = n.commands.flatMap((c) =>
        [c.path.at(-1)!, ...c.aliases].map((w) => item(w, c.description))
      );
      const optItems = n.options.flatMap((o) =>
        [o.long, o.short].filter((x): x is string => Boolean(x)).map((w) => item(w, o.description))
      );
      return [`    ${sq(key(n.path))})`, `      cmds=(${cmdItems.join(" ")})`, `      opts=(${optItems.join(" ")});;`];
    }),
    `  esac`,
    `  if [[ "$PREFIX" == -* ]]; then`,
    `    _describe -t options 'option' opts`,
    `  else`,
    `    _describe -t commands 'command' cmds`,
    `    (( \${#cmds} )) || _files`,
    `  fi`,
    `}`,
    `if [ "$funcstack[1]" = "${fn}" ]; then`,
    `  ${fn} "$@"`,
    `else`,
    `  compdef ${fn} ${name}`,
    `fi`,
  ];
  return `${lines.join("\n")}\n`;
}

function fish(root: CommandNode, name: string): string {
  const fn = `__${name}_path`;
  const rootKey = "root";
  const k = (path: string[]): string => (path.length ? key(path) : rootKey);
  const lines: string[] = [
    `# fish completion for ${name}, generated by \`${name} completion fish\``,
    `function ${fn}`,
    `  set -l cpath ${rootKey}`,
    `  set -l tokens (commandline -opc)`,
    `  set -e tokens[1]`,
    `  for w in $tokens`,
    `    switch "$cpath/$w"`,
    ...transitions(root).flatMap((t) => [
      `      case ${fishSq(`${t.from || rootKey}/${t.word}`)}`,
      `        set cpath ${fishSq(t.to)}`,
    ]),
    `    end`,
    `  end`,
    `  echo $cpath`,
    `end`,
    `complete -c ${name} -f`,
  ];
  for (const n of flat(root)) {
    const cond = `-n ${fishSq(`test (${fn}) = ${fishSq(k(n.path))}`)}`;
    for (const c of n.commands) {
      for (const w of [c.path.at(-1)!, ...c.aliases]) {
        lines.push(`complete -c ${name} ${cond} -a ${fishSq(w)} -d ${fishSq(c.description)}`);
      }
    }
    for (const o of n.options) {
      const parts = [`complete -c ${name} ${cond}`];
      if (o.short) parts.push(`-s ${o.short.replace(/^-/, "")}`);
      if (o.long) parts.push(`-l ${o.long.replace(/^--/, "")}`);
      const choices = [o.long, o.short].map((f) => (f ? FLAG_VALUE_CHOICES[f] : undefined)).find(Boolean);
      if (choices) parts.push(`-x -a ${fishSq(choices.join(" "))}`);
      else if (o.takesValue) parts.push("-r");
      parts.push(`-d ${fishSq(o.description)}`);
      lines.push(parts.join(" "));
    }
  }
  return `${lines.join("\n")}\n`;
}

/** Generate the completion script for `shell` from the live command tree under `root`. */
export function generateCompletion(shell: CompletionShell, root: Command): string {
  const tree = walkCommands(root);
  const name = root.name();
  if (shell === "bash") return bash(tree, name);
  if (shell === "zsh") return zsh(tree, name);
  return fish(tree, name);
}

